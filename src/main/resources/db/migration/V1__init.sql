-- A small enterprise social network: each enterprise (tenant) has users, each user has
-- a profile, publishes posts with images, and likes posts.
--
--   belongsTo       users.enterprise_id, profiles.user_id, posts.user_id, images.post_id
--   hasMany         enterprise → users, user → posts, post → images
--   hasOne          user → profile            (enforced by UNIQUE (user_id))
--   hasManyThrough  enterprise → posts, through users
--   manyToMany      users ↔ posts, through post_likes

CREATE TABLE enterprises (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RESTRICT: an enterprise that still has users cannot be deleted.
    enterprise_id BIGINT       NOT NULL REFERENCES enterprises (id) ON DELETE RESTRICT,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);
CREATE INDEX idx_users_enterprise_id ON users (enterprise_id, id);

CREATE TABLE profiles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    bio        VARCHAR(500),
    avatar_url VARCHAR(500),
    -- hasOne: at most one profile per user; also the conflict target of the profile upsert.
    CONSTRAINT uq_profiles_user_id UNIQUE (user_id)
);

CREATE TABLE posts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content    VARCHAR(5000) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL
);
-- Serves "posts of a user, newest first" (keyset pagination on id).
CREATE INDEX idx_posts_user_id ON posts (user_id, id);

CREATE TABLE images (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id  BIGINT       NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    url      VARCHAR(500) NOT NULL,
    -- Display order within the post; at most 10 images per post.
    position INT          NOT NULL,
    CONSTRAINT ck_images_position CHECK (position BETWEEN 1 AND 10),
    CONSTRAINT uq_images_post_position UNIQUE (post_id, position)
);

CREATE TABLE post_likes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- A user likes a post at most once; also the conflict target of the idempotent like.
    CONSTRAINT uq_post_likes_post_user UNIQUE (post_id, user_id)
);
CREATE INDEX idx_post_likes_user_id ON post_likes (user_id, post_id);

-- Client-supplied Idempotency-Key of POST /posts, scoped per user.
-- A retried request with the same key returns the post created by the first one.
CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    idempotency_key VARCHAR(128) NOT NULL,
    -- SHA-256 of the request body: the same key with a different body is rejected.
    request_hash    CHAR(64)     NOT NULL,
    -- SET NULL: deleting the post keeps the key used, so a late retry cannot re-create it.
    post_id         BIGINT       REFERENCES posts (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_idempotency_keys_user_key UNIQUE (user_id, idempotency_key)
);
CREATE INDEX idx_idempotency_keys_post_id ON idempotency_keys (post_id);
